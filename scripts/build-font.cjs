// Build src/render/font-data.js: a small anti-aliased bitmap font for the
// software PNG renderer (src/render/raster.js), which has no access to system
// fonts. Glyphs are DejaVu Sans (Bitstream Vera license: free to use and
// embed) drawn by Chromium at SIZE px and stored as 4-bit alpha.
//
//   node scripts/build-font.cjs        (needs Playwright with Chromium, and DejaVu Sans installed)
const { chromium } = require("playwright");
const { writeFileSync } = require("node:fs");

const SIZE = 28;
const CHARS = [...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)), ..."²³¹⁰⁴⁵⁶⁷⁸⁹⁻ⁿ⁺≤≥≠·×±∓∞πθαβγδΔελμσφω∈∩∪→√…−°"];

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const data = await page.evaluate(({ SIZE, CHARS }) => {
    const c = document.createElement("canvas");
    c.width = SIZE * 3;
    c.height = SIZE * 3;
    const g = c.getContext("2d", { willReadFrequently: true });
    g.font = `${SIZE}px "DejaVu Sans"`;
    const m = g.measureText("Hg");
    const ascent = m.fontBoundingBoxAscent;
    const descent = m.fontBoundingBoxDescent;
    const ox = SIZE;
    const oy = SIZE * 2;
    const glyphs = {};
    for (const ch of CHARS) {
      g.clearRect(0, 0, c.width, c.height);
      g.fillStyle = "#000";
      g.textBaseline = "alphabetic";
      g.fillText(ch, ox, oy);
      const img = g.getImageData(0, 0, c.width, c.height).data;
      let x0 = c.width, y0 = c.height, x1 = -1, y1 = -1;
      for (let y = 0; y < c.height; y++)
        for (let x = 0; x < c.width; x++)
          if (img[(y * c.width + x) * 4 + 3] > 8) {
            if (x < x0) x0 = x;
            if (x > x1) x1 = x;
            if (y < y0) y0 = y;
            if (y > y1) y1 = y;
          }
      const adv = g.measureText(ch).width;
      if (x1 < 0) {
        glyphs[ch] = [adv, 0, 0, 0, 0, ""];
        continue;
      }
      const w = x1 - x0 + 1;
      const h = y1 - y0 + 1;
      let hex = "";
      for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) hex += Math.round(img[(y * c.width + x) * 4 + 3] / 17).toString(16);
      glyphs[ch] = [Math.round(adv * 100) / 100, x0 - ox, y0 - oy, w, h, hex];
    }
    return { ascent, descent, glyphs };
  }, { SIZE, CHARS });
  await browser.close();
  const lines = [
    "// Generated by scripts/build-font.cjs: DejaVu Sans glyphs (Bitstream Vera license),",
    `// rendered at ${SIZE}px as 4-bit alpha (one hex digit per pixel).`,
    "// Each glyph: [advance, left, top (from the baseline, negative up), width, height, alpha].",
    `export const FONT_SIZE = ${SIZE};`,
    `export const ASCENT = ${Math.round(data.ascent * 100) / 100};`,
    `export const DESCENT = ${Math.round(data.descent * 100) / 100};`,
    "export const GLYPHS = {",
    ...Object.entries(data.glyphs).map(([ch, g]) => `  ${JSON.stringify(ch)}: ${JSON.stringify(g)},`),
    "};",
    "",
  ];
  writeFileSync("src/render/font-data.js", lines.join("\n"));
  console.log(`${Object.keys(data.glyphs).length} glyphs written to src/render/font-data.js`);
})();
